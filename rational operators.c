#include<stdio.h>
int  main()
{
    int n1,n2;
    printf("rational operators \n");
    n1=6;
    n2=7;
    printf("%d \n",n1==n2);
    printf("%d \n",n1<n2);
    printf("%d \n",n1>n2);
    printf("%d \n",n1<=n2);
    printf("%d \n",n1>=n2);
    printf("%d \n",n1!=n2);
    return 0;
}
